const metaDescription = document.querySelector('meta[name="description"]');
const i18nNodes = document.querySelectorAll('[data-i18n]');
const langButtons = document.querySelectorAll('.lang-btn');
const typedRole = document.getElementById('hero-typed-role');
const navToggle = document.querySelector('.nav-toggle');
const siteNav = document.querySelector('.site-nav');
const navLinks = document.querySelectorAll('.site-nav a[href^="#"]');
const revealItems = document.querySelectorAll('.reveal');
const statValues = document.querySelectorAll('.stat-value[data-target]');
const copyEmailButton = document.getElementById('copy-email');
const copyFeedback = document.getElementById('copy-feedback');
const currentYear = document.getElementById('current-year');
const tiltCards = document.querySelectorAll('.tilt-card');
const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

let currentLanguage = localStorage.getItem('site-language') || 'en';
let typingRoleIndex = 0;
let typingCharIndex = 0;
let typingDeleting = false;
let typingTimeoutId;

if (currentYear) {
    currentYear.textContent = new Date().getFullYear();
}

function getValueByPath(source, path) {
    return path.split('.').reduce((accumulator, key) => accumulator && accumulator[key], source);
}

function applyTranslations(language) {
    const dictionary = translations[language] || translations.en;

    document.documentElement.lang = language;
    document.title = dictionary.title;

    if (metaDescription) {
        metaDescription.setAttribute('content', dictionary.metaDescription);
    }

    i18nNodes.forEach((node) => {
        const key = node.dataset.i18n;
        const value = getValueByPath(dictionary, key);

        if (typeof value === 'string') {
            node.textContent = value;
        }
    });

    if (copyFeedback) {
        copyFeedback.textContent = '';
    }

    langButtons.forEach((button) => {
        const isActive = button.dataset.lang === language;
        button.classList.toggle('active', isActive);
        button.setAttribute('aria-pressed', String(isActive));
    });
}

function stepTypedRoles() {
    if (!typedRole) {
        return;
    }

    const roles = translations[currentLanguage].roles;
    const currentText = roles[typingRoleIndex] || '';

    if (!typingDeleting) {
        typingCharIndex += 1;
        typedRole.textContent = currentText.slice(0, typingCharIndex);

        if (typingCharIndex >= currentText.length) {
            typingDeleting = true;
            typingTimeoutId = window.setTimeout(stepTypedRoles, 1300);
            return;
        }

        typingTimeoutId = window.setTimeout(stepTypedRoles, 68);
        return;
    }

    typingCharIndex -= 1;
    typedRole.textContent = currentText.slice(0, typingCharIndex);

    if (typingCharIndex <= 0) {
        typingDeleting = false;
        typingRoleIndex = (typingRoleIndex + 1) % roles.length;
        typingTimeoutId = window.setTimeout(stepTypedRoles, 180);
        return;
    }

    typingTimeoutId = window.setTimeout(stepTypedRoles, 34);
}

function resetTypedRoles() {
    window.clearTimeout(typingTimeoutId);
    typingRoleIndex = 0;
    typingCharIndex = 0;
    typingDeleting = false;

    if (typedRole) {
        typedRole.textContent = '';
    }

    if (!prefersReducedMotion) {
        stepTypedRoles();
    } else if (typedRole) {
        typedRole.textContent = translations[currentLanguage].roles[0];
    }
}

function setLanguage(language) {
    currentLanguage = translations[language] ? language : 'en';
    localStorage.setItem('site-language', currentLanguage);
    applyTranslations(currentLanguage);
    resetTypedRoles();
}

applyTranslations(currentLanguage);
resetTypedRoles();

langButtons.forEach((button) => {
    button.addEventListener('click', () => {
        setLanguage(button.dataset.lang);
    });
});

if (navToggle && siteNav) {
    navToggle.addEventListener('click', () => {
        const isOpen = siteNav.classList.toggle('open');
        navToggle.setAttribute('aria-expanded', String(isOpen));
        document.body.classList.toggle('menu-open', isOpen);
    });

    navLinks.forEach((link) => {
        link.addEventListener('click', () => {
            siteNav.classList.remove('open');
            navToggle.setAttribute('aria-expanded', 'false');
            document.body.classList.remove('menu-open');
        });
    });
}

const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) {
            return;
        }

        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
    });
}, {
    threshold: 0.18
});

revealItems.forEach((item) => revealObserver.observe(item));

function animateStat(element) {
    const target = Number(element.dataset.target || 0);
    const prefix = element.dataset.prefix || '';
    const suffix = element.dataset.suffix || '';
    const duration = 1200;
    const start = performance.now();

    function step(timestamp) {
        const progress = Math.min((timestamp - start) / duration, 1);
        const value = target * progress;
        const displayValue = target >= 10 ? String(Math.round(value)) : value.toFixed(1).replace('.0', '');
        element.textContent = `${prefix}${displayValue}${suffix}`;

        if (progress < 1) {
            window.requestAnimationFrame(step);
        } else {
            element.textContent = `${prefix}${target}${suffix}`;
        }
    }

    window.requestAnimationFrame(step);
}

const statsObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) {
            return;
        }

        animateStat(entry.target);
        observer.unobserve(entry.target);
    });
}, {
    threshold: 0.75
});

statValues.forEach((value) => statsObserver.observe(value));

const sections = Array.from(document.querySelectorAll('main section[id]'));

const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) {
            return;
        }

        const id = entry.target.getAttribute('id');

        navLinks.forEach((link) => {
            const isActive = link.getAttribute('href') === `#${id}`;
            link.classList.toggle('active', isActive);
        });
    });
}, {
    threshold: 0.45,
    rootMargin: '-15% 0px -35% 0px'
});

sections.forEach((section) => sectionObserver.observe(section));

if (!prefersReducedMotion) {
    tiltCards.forEach((card) => {
        card.addEventListener('pointermove', (event) => {
            const rect = card.getBoundingClientRect();
            const offsetX = event.clientX - rect.left;
            const offsetY = event.clientY - rect.top;
            const tiltStrength = Number(card.dataset.tilt || 10);
            const rotateY = ((offsetX / rect.width) - 0.5) * tiltStrength;
            const rotateX = (0.5 - (offsetY / rect.height)) * tiltStrength;

            card.style.transform = `perspective(1000px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) translateY(-4px)`;
            card.style.setProperty('--glow-x', `${(offsetX / rect.width) * 100}%`);
            card.style.setProperty('--glow-y', `${(offsetY / rect.height) * 100}%`);
        });

        card.addEventListener('pointerleave', () => {
            card.style.transform = '';
            card.style.removeProperty('--glow-x');
            card.style.removeProperty('--glow-y');
        });
    });
}

if (copyEmailButton && copyFeedback) {
    copyEmailButton.addEventListener('click', async () => {
        const email = copyEmailButton.dataset.email;

        try {
            await navigator.clipboard.writeText(email);
            copyFeedback.textContent = translations[currentLanguage].copyEmailSuccess;
        } catch (error) {
            copyFeedback.textContent = translations[currentLanguage].copyEmailFail;
        }
    });
}
